#Requires -Version 7.2
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Addon,
    [string]$Target = 'Mists',
    [ValidateSet('Both', 'CurseForge', 'GitHub')][string]$Channel = 'Both',
    [string]$WorkspaceRoot = (Split-Path $PSScriptRoot -Parent),
    [string]$OutputRoot,
    [switch]$ValidateOnly,
    [switch]$KeepStaging
)

$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Release.Common.ps1')
$workspacePath = (Resolve-Path -LiteralPath $WorkspaceRoot).Path
$profile = Get-YiboReleaseProfile $workspacePath $Addon $Target
if (-not $OutputRoot) { $OutputRoot = Join-Path $workspacePath 'Builds' }
$outputPath = [IO.Path]::GetFullPath($OutputRoot)
if ($outputPath.Equals($profile.Root, [StringComparison]::OrdinalIgnoreCase) -or
    $outputPath.StartsWith($profile.Root + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'OutputRoot must be outside the addon source directory.'
}
$publicEntries = @(Get-YiboPublicEntries $profile.Root)
$sourceHash = Get-YiboSourceDigest ($publicEntries + [pscustomobject]@{
    Relative = 'build-config/ReleaseProfiles.psd1'; Source = (Join-Path $PSScriptRoot 'ReleaseProfiles.psd1'); Content = $null
})
$runtimeEntries = @(Get-YiboTocEntries $profile)
$tocText = $profile.TocText
if ($profile.Addon -eq 'YiboCore') {
    $versions = Get-YiboPackagedAddonVersions $workspacePath $profile
    $lines = @('-- Generated by the Yibo release packager.', 'local Core = _G.YiboCore', 'Core.PackagedAddonVersions = {')
    foreach ($name in $versions.Keys) {
        $safeVersion = $versions[$name].Replace('\', '\\').Replace('"', '\"')
        $lines += '    ["{0}"] = "{1}",' -f $name, $safeVersion
    }
    $lines += '}'
    if ($tocText -notmatch '(?m)^Runtime\\AddonStatus\.lua\s*$' -or $tocText -match 'Data[\\/]PackagedAddonVersions.lua') {
        throw 'Core TOC must contain one unmodified AddonStatus load point.'
    }
    $tocText = $tocText.Replace('Runtime\AddonStatus.lua', "Data\PackagedAddonVersions.lua`nRuntime\AddonStatus.lua")
    $runtimeEntries += [pscustomobject]@{ Relative = 'Data/PackagedAddonVersions.lua'; Source = $null; Content = ($lines -join "`n") }
}
$runtimeEntries = @([pscustomobject]@{ Relative = $profile.Client.LoadToc; Source = $null; Content = $tocText }) + $runtimeEntries
foreach ($relative in $profile.Definition.ExtraFiles) {
    $runtimeEntries += [pscustomobject]@{ Relative = $relative; Source = (Resolve-YiboSourceFile $profile.Root $relative); Content = $null }
}
foreach ($directory in $profile.Definition.ResourceDirectories) {
    foreach ($file in (Get-ChildItem -LiteralPath (Join-Path $profile.Root $directory) -File -Filter '*.tga')) {
        $relative = "$directory/$($file.Name)"
        if ($relative -notin $runtimeEntries.Relative) {
            $runtimeEntries += [pscustomobject]@{ Relative = $relative; Source = (Resolve-YiboSourceFile $profile.Root $relative); Content = $null }
        }
    }
}
Test-YiboLuaEntries $runtimeEntries $profile.Client.LuaVersion

$targetStates = foreach ($id in ($profile.Definition.Targets.Keys | Sort-Object)) {
    $otherProfile = Get-YiboReleaseProfile $workspacePath $profile.Addon $id
    [ordered]@{
        target = $otherProfile.Target; slug = $otherProfile.Slug; gameVersionNames = @($otherProfile.Client.CurseForgeVersionNames)
        version = $otherProfile.Version; publicAPI = $otherProfile.APIVersion
        minimumCoreAPI = $otherProfile.RequiredCoreAPI; sourceToc = $otherProfile.Client.SourceToc
        loadToc = $otherProfile.Client.LoadToc; interface = @($otherProfile.Interfaces)
        validationState = $otherProfile.Client.ValidationState
    }
}
$baseManifest = [ordered]@{
    schemaVersion = 1; addon = $profile.Addon; sourceSHA256 = $sourceHash
    registeredTargets = @($targetStates)
}
$cfManifest = [ordered]@{} + $baseManifest
$cfManifest.channel = 'CurseForge'
$cfManifest.target = $profile.Target
$cfManifest.slug = $profile.Slug
$cfManifest.curseForge = [ordered]@{
    flavor = $profile.Client.CurseForgeFlavor; gameVersionNames = @($profile.Client.CurseForgeVersionNames)
    uploadState = 'requires-current-game-version-id-resolution'
}
$cfManifest.files = @($runtimeEntries.Relative)
$ghManifest = [ordered]@{} + $baseManifest
$ghManifest.channel = 'GitHub'
$ghManifest.purpose = 'all-target-source-and-public-documentation'
$ghManifest.buildProfiles = $profile.Config
$ghManifest.files = @($publicEntries.Relative)
$manifestName = 'YiboReleaseManifest.json'
if ($manifestName -in $publicEntries.Relative -or $manifestName -in $runtimeEntries.Relative) { throw 'Generated release manifest already exists in source.' }
$cfEntries = $runtimeEntries + [pscustomobject]@{ Relative = $manifestName; Source = $null; Content = ($cfManifest | ConvertTo-Json -Depth 12) }
$ghEntries = $publicEntries + [pscustomobject]@{ Relative = $manifestName; Source = $null; Content = ($ghManifest | ConvertTo-Json -Depth 12) }
$names = Get-YiboPackageNames -Addon $profile.Addon -Slug $profile.Slug -Version $profile.Version -PublicAPI $profile.APIVersion -VersionIncludesAPI $profile.Definition.VersionIncludesAPI -SourceHash $sourceHash -SourceTargets @($targetStates)
$cfName, $ghName = $names.CurseForge, $names.GitHub
$artifacts = @()
if ($Channel -in @('Both', 'CurseForge')) { $artifacts += [pscustomobject]@{ Channel = 'CurseForge'; Final = (Join-Path $outputPath $cfName); Entries = $cfEntries } }
if ($Channel -in @('Both', 'GitHub')) { $artifacts += [pscustomobject]@{ Channel = 'GitHub'; Final = (Join-Path $outputPath $ghName); Entries = $ghEntries } }
$plan = [pscustomobject]@{
    Addon = $profile.Addon; Target = $profile.Target; Version = $profile.Version; APIVersion = $profile.APIVersion
    SourceSHA256 = $sourceHash; SourceToc = $profile.Client.SourceToc; LoadToc = $profile.Client.LoadToc
    Interface = $profile.Interfaces; Channel = $Channel; ValidationOnly = [bool]$ValidateOnly
    CurseForge = $(if ($Channel -in @('Both', 'CurseForge')) { Join-Path $outputPath $cfName } else { $null })
    GitHub = $(if ($Channel -in @('Both', 'GitHub')) { Join-Path $outputPath $ghName } else { $null })
    Archived = 0
}
if ($ValidateOnly) { return $plan }
foreach ($artifact in $artifacts) {
    if (Test-Path -LiteralPath $artifact.Final) { throw "Package already exists: $($artifact.Final)" }
}
if ($profile.Addon -eq 'YiboCore') {
    $checker = Resolve-YiboSourceFile $workspacePath 'Tools/Check-Localization.py'
    $report = Join-Path $workspacePath "_NonRelease/Localization/Build/YiboCore-$($profile.Target)-LocalizationReport.md"
    & python $checker --addon YiboCore --output $report | Out-Host
    if ($LASTEXITCODE -ne 0) { throw 'Localization report generation failed.' }
    Write-Host "Review localization candidates and client acceptance before distribution: $report"
}
[void](New-Item -ItemType Directory -Path $outputPath -Force)
$runID = [guid]::NewGuid().ToString('N')
foreach ($artifact in $artifacts) {
    $temporary = $artifact.Final + '.building-' + $runID
    $artifact | Add-Member -NotePropertyName Temporary -NotePropertyValue $temporary
    New-YiboPackage $temporary $profile.Addon $artifact.Entries
}
if ((Get-YiboSourceDigest ($publicEntries + [pscustomobject]@{
    Relative = 'build-config/ReleaseProfiles.psd1'; Source = (Join-Path $PSScriptRoot 'ReleaseProfiles.psd1'); Content = $null
})) -ne $sourceHash) { throw 'Source or release configuration changed during packaging; completed intermediates were retained.' }
$plan.Archived = Publish-YiboPackages $outputPath $profile $artifacts
# Completed intermediates are moved into place; failures retain their files for diagnosis.
return $plan
