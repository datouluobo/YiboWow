"""Generate the Forever armor-kit catalog from same-build client DB2 CSV exports."""

import argparse
import csv
from collections import defaultdict
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[2] / "Forever" / "Data" / "ArmorKits.lua"
LEATHERWORKING = 165
CREATE_ITEM = 24
ENCHANT_ITEM = 53


def table(directory, name):
    with (directory / f"{name}.csv").open(encoding="utf-8-sig", newline="") as source:
        yield from csv.DictReader(source)


def generate(directory, build):
    recipes = {
        int(row["Spell"]) for row in table(directory, "SkillLineAbility")
        if int(row["SkillLine"]) == LEATHERWORKING
    }
    enchantments = {int(row["ID"]) for row in table(directory, "SpellItemEnchantment")}
    crafted_items = set()
    applications = defaultdict(set)
    for row in table(directory, "SpellEffect"):
        effect, spell = int(row["Effect"]), int(row["SpellID"])
        if effect == CREATE_ITEM and spell in recipes:
            crafted_items.add(int(row["EffectItemType"]))
        if effect == ENCHANT_ITEM:
            enchantment = int(row["EffectMiscValue_0"])
            if enchantment in enchantments:
                applications[spell].add(enchantment)

    # Forever stores the item-to-effect relation in ItemXItemEffect.
    use_spells = {
        int(row["ID"]): int(row["SpellID"]) for row in table(directory, "ItemEffect")
        if int(row["TriggerType"]) == 0
    }
    items_by_enchantment = defaultdict(set)
    for row in table(directory, "ItemXItemEffect"):
        spell = use_spells.get(int(row["ItemEffectID"]))
        for enchantment in applications.get(spell, ()):
            items_by_enchantment[enchantment].add(int(row["ItemID"]))

    # Unnamed item records also have use effects, but lack a player-facing item
    # in this build. Use the named items to resolve identity.
    named_items = {
        int(row["ID"]) for row in table(directory, "ItemSparse") if row["Display_lang"].strip()
    }
    # Consumables / permanent item enhancements. This excludes unrelated crafted goods.
    icons = {
        int(row["ID"]): int(row["IconFileDataID"]) for row in table(directory, "Item")
        if int(row["ID"]) in crafted_items and (row["ClassID"], row["SubclassID"]) == ("0", "6")
    }
    if items_by_enchantment.get(15) != {2304} or not icons.get(2304):
        raise ValueError("Client sample enchantment 15 must resolve uniquely to Light Armor Kit (2304)")

    lines = [
        f"-- Generated by GenerateForeverArmorKits.py from Forever DB2 build {build}.",
        "-- Key is the permanent enchantment ID. Values provide item and icon IDs.",
        "-- Entries without an item ID represent multiple named Leatherworking armor kits.",
        "_G.YiboBuilds.ForeverArmorKits = {",
    ]
    for enchantment, items in sorted(items_by_enchantment.items()):
        items = items & named_items
        if not items or not items <= icons.keys():
            continue
        if len(items) > 1:
            distinct_icons = {icons[item] for item in items}
            icon = f" icon = {next(iter(distinct_icons))} " if len(distinct_icons) == 1 else ""
            lines.append(f"    [{enchantment}] = {{{icon}}},")
        else:
            item = next(iter(items))
            lines.append(f"    [{enchantment}] = {{ itemID = {item}, icon = {icons[item]} }},")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv_directory", type=Path, help="Directory containing the seven same-build DB2 CSV files")
    parser.add_argument("--build", required=True)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    catalog = generate(args.csv_directory, args.build)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(catalog, encoding="utf-8", newline="\n")
