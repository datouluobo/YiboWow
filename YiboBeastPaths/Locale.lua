ns.LocaleResources = {}
RegisterResources({ Locale = { Register = function(_, owner, language, resources)
    ns.LocaleResources[language] = resources
end } })

local registeredCore
function ns.RegisterLocale(core)
    if core and registeredCore == core then return true end
    if not (core and core.CheckAPIVersion and core:CheckAPIVersion(13)
        and core.HasCapability and core:HasCapability("localization", 1)
        and core.IsInitialized and core:IsInitialized()
        and core.Locale and core.Locale.Register and core.Locale.Get) then return false end
    RegisterResources(core)
    registeredCore = core
    return true
end

function ns.Text(key, ...)
    local core = _G.YiboCore
    if ns.RegisterLocale(core) then
        return core.Locale:Get("YiboBeastPaths", key, ...)
    end
    -- Explicit standalone compatibility: Core is optional for map routes.
    -- Hosted maintenance never initializes without the API13 contract.
    local locale = GetLocale and GetLocale() or "enUS"
    local language = (locale == "zhCN" or locale == "zhTW") and "zh" or "en"
    local text = ns.LocaleResources[language][key] or ("[YiboBeastPaths:" .. key .. "]")
    return select("#", ...) > 0 and string.format(text, ...) or text
end
ns.RegisterLocale(Core)
